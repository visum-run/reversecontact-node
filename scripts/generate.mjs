import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const snapshot = new URL('../../openapi/public-v2.json', import.meta.url)
if (!existsSync(snapshot)) {
  console.log(
    'Skipping type generation: the monorepo OpenAPI snapshot is absent. Using committed types.'
  )
} else {
  execFileSync(
    process.execPath,
    [
      fileURLToPath(new URL('../node_modules/openapi-typescript/bin/cli.js', import.meta.url)),
      fileURLToPath(snapshot),
      '-o',
      fileURLToPath(new URL('../src/generated/openapi.ts', import.meta.url)),
      '--default-non-nullable',
      'false'
    ],
    { stdio: 'inherit' }
  )
  writeFileSync(
    new URL('../src/generated/catalogs.ts', import.meta.url),
    renderCatalogs(JSON.parse(readFileSync(snapshot, 'utf8')).components.schemas)
  )
}

/** "Owner / Founder" → OWNER_FOUNDER, "MC:DACH" → MC_DACH, "Arts & Crafts" → ARTS_AND_CRAFTS. */
function constantName(value) {
  return value
    .normalize('NFD')
    .replace(/\p{Diacritic}/gu, '')
    .replace(/&/g, ' and ')
    .replace(/\+/g, ' plus ')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .replace(/^_+|_+$/g, '')
    .toUpperCase()
}

/**
 * Every named string enum of the spec (Industry, Area...) becomes a constant
 * object and the type of its values. The request parameters stay open to any
 * string (see `Body` in src/types.ts), so the constants are a convenience.
 */
function renderCatalogs(schemas) {
  const catalogs = Object.entries(schemas).filter(
    ([, schema]) => schema.type === 'string' && Array.isArray(schema.enum)
  )
  let text =
    '// Generated by scripts/generate.mjs from the OpenAPI snapshot. Do not edit by hand.\n'
  for (const [name, schema] of catalogs) {
    const seen = new Map()
    const members = schema.enum.map(value => {
      const key = constantName(value)
      if (!/^[A-Z_][A-Z0-9_]*$/.test(key))
        throw new Error(`${name}: no constant name for "${value}"`)
      if (seen.has(key)) {
        throw new Error(`${name}: "${seen.get(key)}" and "${value}" share the name ${key}`)
      }
      seen.set(key, value)
      return `  ${key}: ${JSON.stringify(value)}`
    })
    text += `\n/** ${schema.description ?? name} */\n`
    text += `export const ${name} = {\n${members.join(',\n')}\n} as const\n`
    text += `export type ${name} = (typeof ${name})[keyof typeof ${name}]\n`
  }
  text += `\n/** Any value of a published list. */\nexport type CatalogValue =\n${catalogs
    .map(([name]) => `  | ${name}`)
    .join('\n')}\n`
  return text
}
